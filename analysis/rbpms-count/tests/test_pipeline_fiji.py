"""End-to-end test of the tiling pipeline, in Fiji.

Everything it needs is generated by Fiji into a temporary folder (see make_test_images.groovy):
no image is committed and nothing is written inside the repository. The expensive part -- making
the images, counting them twice, resuming, reviewing -- happens once in setUpClass; the test
methods only look at what came out.

Skipped when Fiji is not installed. Set RBPMS_TEST_FIJI=1 to make a missing Fiji a failure.
"""
import csv
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parents[0] / "scripts"
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import rbpms  # noqa: E402
import tiling  # noqa: E402

SAMPLE = "9000L"
CELLS = {"9000L_a1": 35, "9000L_a2": 2, "9000L_dpi": 2}
TILE_PX, FLAT_TILE_PX = 600, 2000
UM = 0.227
MEM = "3g"


def read(path) -> list[dict]:
    with open(path, newline="", encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def mtimes(paths) -> dict:
    return {p: p.stat().st_mtime_ns for p in paths}


class TestPipeline(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        try:
            rbpms.find_fiji()
        except FileNotFoundError:
            if os.environ.get("RBPMS_TEST_FIJI") == "1":
                raise
            raise unittest.SkipTest("Fiji is not installed (set RBPMS_TEST_FIJI=1 to require it)")
        cls._tmp = tempfile.TemporaryDirectory(prefix="rbpms-fiji-")
        tmp = Path(cls._tmp.name)
        cls.data = tmp / "data"
        cls.tiled, cls.flat, cls.tilesonly = tmp / "out_tiled", tmp / "out_flat", tmp / "out_tiles"
        cls.tracking = tmp / "tracking"
        cls.data.mkdir()

        cls._fiji(HERE / "make_test_images.groovy", dict(outDir=cls.data.as_posix()))
        src = sorted((cls.data / SAMPLE).iterdir())
        cls.sources = {p.name: (p.stat().st_size, p.stat().st_mtime_ns) for p in src}

        # the whole point: the same images counted in 4 tiles and in one piece
        cls._count(cls.tiled, TILE_PX)
        cls._count(cls.flat, FLAT_TILE_PX)
        cls.survey = rbpms.inspect(cls.data, cls.tiled, tile_px=TILE_PX, memory=MEM)
        cls.tile_table = rbpms.tile(cls.data, cls.tilesonly, tile_px=TILE_PX, memory=MEM)
        cls._resume()
        cls._fiji(SCRIPTS / "review_counts.groovy",
                  dict(runDir=cls.tiled.as_posix(), reviewer="TEST", samples="", redo=False,
                       simulate=True))

    @classmethod
    def _fiji(cls, script, args):
        code = rbpms.run_fiji_script(script, args, memory="2g")
        assert code == 0, f"{Path(script).name} failed with code {code}"

    @classmethod
    def _count(cls, output, tile_px):
        code = rbpms.count(cls.data, output, tile_px=tile_px, memory=MEM)
        assert code == 0, f"count(tile_px={tile_px}) failed with code {code}"

    @classmethod
    def _resume(cls):
        """Throw away the last tile of the tiled image and count again."""
        tiles_csv = cls.tiled / "counts" / "tiles.csv"
        cls.dropped = [r for r in read(tiles_csv) if r["image"] == "9000L_a1"][-1]
        gone = cls.dropped["tile"]
        header, *body = tiles_csv.read_text(encoding="utf-8").splitlines()
        body = [ln for ln in body if ln.split(",")[2] != gone]
        tiles_csv.write_text("\n".join([header] + body) + "\n", encoding="utf-8")
        for p in [cls.tiled / "tiles" / SAMPLE / "9000L_a1" / f"{gone}.tif",
                  cls.tiled / "counted" / SAMPLE / f"{gone}.tif",
                  cls.tiled / "counted" / SAMPLE / f"{gone}.jpg"]:
            p.unlink()
        cls.untouched = mtimes(sorted((cls.tiled / "counted" / SAMPLE).glob("*.tif"))
                               + [cls.tiled / "normalized" / SAMPLE / "9000L_a1.tif"])
        cls._count(cls.tiled, TILE_PX)
        cls.untouched_after_resume = mtimes(list(cls.untouched))

    # ------------------------------------------------------------------ inspect
    def test_inspect_reads_the_metadata_of_every_format(self):
        by = {r["image"]: r for r in read(self.tiled / "counts" / "images.csv")}
        self.assertEqual(set(by), {"9000L_a1", "9000L_a2", "9000L_dpi", "9000L_broken"})
        a1 = by["9000L_a1"]
        self.assertEqual((a1["width_px"], a1["height_px"]), ("1200", "1000"))
        self.assertEqual((a1["channels"], a1["z"], a1["t"]), ("2", "2", "1"))
        self.assertAlmostEqual(float(a1["um_per_px"]), UM, places=3)
        self.assertEqual(a1["problem"], "")
        # a plain TIFF with no calibration must not be believed to be 353 um per pixel
        self.assertEqual(by["9000L_dpi"]["um_per_px"], "")
        # the non-TIFF source is reported as its own format
        self.assertNotIn("tif", by["9000L_a2"]["format"].lower())
        self.assertTrue(by["9000L_broken"]["problem"], "a corrupt file must be recorded")

    def test_inspect_reports_the_tile_count(self):
        df = self.survey.set_index("image")
        self.assertEqual(int(df.loc["9000L_a1", "tiles"]), 4)
        self.assertEqual(int(df.loc["9000L_a2", "tiles"]), 1)
        self.assertEqual(int(df.loc["9000L_broken", "tiles"]), 0)
        self.assertEqual(int(df.loc["9000L_a1", "margin_px"]), rbpms.derived_margin())

    def test_the_source_images_are_only_read(self):
        # only the files that were there to begin with: Bio-Formats may drop a hidden .bfmemo
        # cache next to them, which the file walk ignores anyway
        now = {name: ((self.data / SAMPLE / name).stat().st_size,
                      (self.data / SAMPLE / name).stat().st_mtime_ns) for name in self.sources}
        self.assertEqual(now, self.sources)

    # ------------------------------------------------------------------ normalize and tile
    def test_every_source_is_normalized_to_a_tif_with_provenance(self):
        norm = self.tiled / "normalized" / SAMPLE
        for name in CELLS:
            self.assertTrue((norm / f"{name}.tif").is_file(), name)
            self.assertTrue((norm / f"{name}.json").is_file(), name)
        prov = json.loads((norm / "9000L_a1.json").read_text(encoding="utf-8"))
        self.assertEqual(prov["channel"], 1)
        self.assertEqual(prov["projection"], "max")        # 2 Z slices were max-projected
        self.assertEqual((prov["width_px"], prov["height_px"]), (1200, 1000))
        self.assertTrue(prov["source"].endswith("9000L_a1.tif"))
        a2 = json.loads((norm / "9000L_a2.json").read_text(encoding="utf-8"))
        self.assertTrue(a2["source"].endswith("9000L_a2.ics"))
        self.assertEqual(a2["projection"], "none")

    def test_a_tiled_image_has_one_padded_tif_per_tile(self):
        want = tiling.plan_tiles(
            tiling.SourceImage(sample=SAMPLE, image="9000L_a1", width_px=1200, height_px=1000),
            TILE_PX, rbpms.derived_margin())
        made = sorted((self.tiled / "tiles" / SAMPLE / "9000L_a1").glob("*.tif"))
        self.assertEqual([p.stem for p in made], [t.tile for t in want])
        # a single-tile image is counted off the normalized image, so it needs no tile file
        self.assertFalse((self.tiled / "tiles" / SAMPLE / "9000L_a2").exists())

    def test_tile_writes_the_tiles_without_counting(self):
        df = self.tile_table
        self.assertEqual(len(df), 4 + 1 + 1)               # a1 in 4 tiles, a2 and dpi in one each
        for p in df["file"]:
            self.assertTrue(Path(p).is_file(), p)
        self.assertFalse((self.tilesonly / "counts" / "tiles.csv").exists())
        self.assertFalse((self.tilesonly / "counted").exists())

    # ------------------------------------------------------------------ the counts add up
    def test_per_tile_counts_add_up_to_the_image_and_match_the_untiled_count(self):
        tiles = read(self.tiled / "counts" / "tiles.csv")
        tiled = {r["image"]: r for r in read(self.tiled / "counts" / "auto_counts.csv")}
        flat = {r["image"]: r for r in read(self.flat / "counts" / "auto_counts.csv")}
        for name, expected in CELLS.items():
            per_tile = sum(int(r["auto_count"]) for r in tiles if r["image"] == name)
            with self.subTest(image=name):
                self.assertEqual(per_tile, int(tiled[name]["auto_count"]),
                                 "the per-tile rows must add up to the image row")
                self.assertEqual(int(tiled[name]["auto_count"]), int(flat[name]["auto_count"]),
                                 "tiling must not change the count")
                self.assertEqual(int(tiled[name]["auto_count"]), expected,
                                 "every synthetic cell must be counted exactly once")
        self.assertEqual((int(tiled["9000L_a1"]["tiles"]), int(flat["9000L_a1"]["tiles"])), (4, 1))
        self.assertNotIn("9000L_broken", tiled)

    def test_the_cores_cover_the_image_and_the_area_uses_the_real_pixel_size(self):
        auto = {r["image"]: r for r in read(self.tiled / "counts" / "auto_counts.csv")}
        self.assertEqual(int(auto["9000L_a1"]["core_px"]), 1200 * 1000)
        self.assertAlmostEqual(float(auto["9000L_a1"]["area_mm2"]), 1200 * 1000 * UM * UM / 1e6,
                               places=5)
        self.assertAlmostEqual(float(auto["9000L_a1"]["cells_per_mm2"]),
                               35 / (1200 * 1000 * UM * UM / 1e6), places=0)
        # unknown pixel size stays unknown rather than becoming a guessed area
        self.assertEqual(auto["9000L_dpi"]["area_mm2"], "")
        self.assertEqual(auto["9000L_dpi"]["cells_per_mm2"], "")

    def test_rois_csv_records_parent_coordinates(self):
        for row in read(self.tiled / "counts" / "tiles.csv"):
            p = self.tiled / "rois" / row["sample"] / f"{row['tile']}_rois.csv"
            with self.subTest(tile=row["tile"]):
                self.assertTrue(p.is_file())
                rois = read(p)
                self.assertTrue(rois, "no objects at all in this tile")
                self.assertEqual(sorted(rois[0]), sorted(tiling.ROIS_COLUMNS))
                kept = [r for r in rois if r["kept"] == "1" and r["in_core"] == "1"]
                self.assertEqual(len(kept), int(row["auto_count"]))
                for r in rois:
                    self.assertAlmostEqual(float(r["parent_x_px"]) - float(r["x_px"]),
                                           float(row["core_x0"]), places=2)
                    self.assertAlmostEqual(float(r["parent_y_px"]) - float(r["y_px"]),
                                           float(row["core_y0"]), places=2)

    def test_a_cell_on_a_tile_boundary_is_counted_by_one_tile_only(self):
        found = []
        for row in read(self.tiled / "counts" / "tiles.csv"):
            if row["image"] != "9000L_a1":
                continue
            for r in read(self.tiled / "rois" / row["sample"] / f"{row['tile']}_rois.csv"):
                if r["kept"] == "1" and r["in_core"] == "1":
                    found.append((float(r["parent_x_px"]), float(r["parent_y_px"])))
        self.assertEqual(len(found), 35)
        # the grid puts cells on the boundaries x=600 and y=600, the corner one on both
        for want in [(600, 600), (600, 150), (150, 600), (1050, 880)]:
            near = [c for c in found if abs(c[0] - want[0]) <= 2 and abs(c[1] - want[1]) <= 2]
            self.assertEqual(len(near), 1, f"cell at {want}: {near}")
        # and at least one object was seen by a neighbouring tile and left to its owner
        self.assertTrue(any(int(r["outside_core"]) > 0
                            for r in read(self.tiled / "counts" / "tiles.csv")))

    def test_a_tiled_image_gets_a_parent_overview(self):
        counted = self.tiled / "counted" / SAMPLE
        self.assertTrue((counted / "9000L_a1.jpg").is_file(), "no parent overview")
        self.assertFalse((counted / "9000L_a1.tif").exists(), "a tiled image has no single tif")
        for t in sorted((self.tiled / "tiles" / SAMPLE / "9000L_a1").glob("*.tif")):
            self.assertTrue((counted / f"{t.stem}.tif").is_file(), t.stem)
            self.assertTrue((counted / f"{t.stem}.jpg").is_file(), t.stem)
        self.assertTrue((counted / "9000L_a2.tif").is_file())

    def test_counted_tifs_are_cropped_to_the_core(self):
        for row in read(self.tiled / "counts" / "tiles.csv"):
            w, h = _tif_size(self.tiled / "counted" / row["sample"] / f"{row['tile']}.tif")
            with self.subTest(tile=row["tile"]):
                self.assertEqual((w, h), (int(row["core_x1"]) - int(row["core_x0"]),
                                          int(row["core_y1"]) - int(row["core_y0"])))

    # ------------------------------------------------------------------ resume
    def test_resume_recounts_only_the_missing_tile(self):
        rows = {r["tile"]: r for r in read(self.tiled / "counts" / "tiles.csv")}
        gone = self.dropped["tile"]
        self.assertIn(gone, rows)
        self.assertEqual(int(rows[gone]["auto_count"]), int(self.dropped["auto_count"]),
                         "recounting a tile must give the same answer")
        self.assertEqual(len([r for r in rows.values() if r["image"] == "9000L_a1"]), 4)
        for p, when in self.untouched.items():
            self.assertEqual(self.untouched_after_resume[p], when, f"{p.name} was rewritten needlessly")

    # ------------------------------------------------------------------ review
    def test_review_writes_tile_rows_that_fold_up_to_images(self):
        tile_man = read(self.tiled / "counts" / "tile_manual_counts.csv")
        self.assertEqual(len(tile_man), 6)                 # 4 tiles of a1, plus a2 and dpi
        self.assertEqual({r["sample"] for r in tile_man}, {SAMPLE})

        df = rbpms.counts(self.tiled, level="image").set_index("image")
        self.assertEqual(sorted(df.index), sorted(CELLS))
        a1 = df.loc["9000L_a1"]
        self.assertTrue(bool(a1["reviewed"]))
        self.assertEqual(int(a1["tiles_reviewed"]), 4)
        self.assertEqual(int(a1["auto_count"]), 35)
        self.assertEqual(int(a1["final_count"]),
                         int(a1["auto_count"]) - int(a1["removed"]) + int(a1["added"]))
        self.assertEqual(int(a1["count"]), int(a1["final_count"]))

        per_tile = rbpms.counts(self.tiled, level="tile")
        self.assertEqual(len(per_tile), 6)
        self.assertEqual(int(per_tile["final_count"].notna().sum()), 6)

    def test_update_log_counts_images_not_tiles(self):
        (self.tracking).mkdir(exist_ok=True)
        (self.tracking / "animals.csv").write_text(
            "animal,eyes,priority,requested,notes\n9000,L,today,2026-11-01,\n", encoding="utf-8")
        st = rbpms.update_log(self.data, self.tiled, tracking=self.tracking)
        row = st[st["folders"] == SAMPLE].iloc[0]
        self.assertEqual(int(row["images"]), 3)            # a1, a2, dpi; broken cannot be read
        self.assertEqual(int(row["counted"]), 3)
        self.assertEqual(int(row["reviewed"]), 3)
        self.assertTrue(str(row["stage"]).startswith("6 reviewed"))
        status = rbpms.review_status(self.tiled).set_index("retina")
        self.assertEqual(int(status.loc[SAMPLE, "images"]), 3)
        self.assertEqual(int(status.loc[SAMPLE, "reviewed"]), 3)
        self.assertEqual(int(status.loc[SAMPLE, "fields"]), 6)


def _tif_size(path):
    """Width and height out of a TIFF header, so the test needs no image library."""
    import struct
    with open(path, "rb") as fh:
        head = fh.read(8)
        endian = "<" if head[:2] == b"II" else ">"
        offset = struct.unpack(endian + "I", head[4:8])[0]
        fh.seek(offset)
        n = struct.unpack(endian + "H", fh.read(2))[0]
        size = {}
        for _ in range(n):
            tag, typ, _count = struct.unpack(endian + "HHI", fh.read(8))
            raw = fh.read(4)
            if tag in (256, 257):
                size[tag] = struct.unpack(endian + ("H" if typ == 3 else "I"),
                                          raw[:2] if typ == 3 else raw)[0]
    return size[256], size[257]


if __name__ == "__main__":
    unittest.main()
